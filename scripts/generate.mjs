#!/usr/bin/env node
// Generate PLUGINS.md (the human-readable catalog) from plugins.json.
//
//   node scripts/generate.mjs [--check]
//
// plugins.json is the only hand-edited file; the markdown is committed so it
// renders on GitHub, and validate/publish workflows re-run this script:
//   --check (used by CI) exits 1 when PLUGINS.md is stale instead of writing.
//
// Zero-dependency, like the other registry scripts.

import { readFileSync, writeFileSync } from "node:fs";

const REGISTRY_PATH = "plugins.json";
const OUTPUT_PATH = "PLUGINS.md";

const checkMode = process.argv.includes("--check");

function githubUrl(repo, ...rest) {
  return [`https://github.com/${repo}`, ...rest].join("/");
}

function kindLabel(plugin) {
  if (plugin.frontend && plugin.backend) return "frontend + rust backend";
  if (plugin.frontend) return "frontend only";
  if (plugin.backend) return "rust backend only";
  return "metadata only";
}

function permissionChips(plugin) {
  return plugin.permissions.map((perm) => `\`${perm}\``).join(" ") || "—";
}

function render(registry) {
  const plugins = registry.plugins ?? [];
  const lines = [];

  lines.push("<!-- DO NOT EDIT — generated by scripts/generate.mjs from plugins.json. -->");
  lines.push("");
  lines.push("# Companion plugin registry");
  lines.push("");
  lines.push(
    `${plugins.length} plugin${plugins.length === 1 ? "" : "s"} · source of truth: [` +
      "`plugins.json`" +
      `](plugins.json) (schema: [` +
      "`schema.json`" +
      "](schema.json)) · to add yours, see [CONTRIBUTING.md](CONTRIBUTING.md).",
  );
  lines.push("");
  lines.push("Registered plugins are listed on the [Companion plugins page]" +
    "(https://companion-lab.github.io/plugins) automatically after a PR merges to `main`.");
  lines.push("");

  lines.push("## Catalog");
  lines.push("");
  lines.push("| Plugin | Version | Permissions | Kind | Repository |");
  lines.push("| ------ | ------- | ----------- | ---- | ---------- |");
  for (const plugin of plugins) {
    lines.push(
      `| [${plugin.name}](${githubUrl(plugin.repo)}) | ${plugin.version} | ` +
        `${permissionChips(plugin)} | ${kindLabel(plugin)} | ${plugin.repo} |`,
    );
  }
  lines.push("");

  lines.push("## Details");
  lines.push("");
  for (const plugin of plugins) {
    lines.push(`### ${plugin.name} — \`${plugin.id}\` v${plugin.version}`);
    lines.push("");
    lines.push(plugin.description);
    lines.push("");
    lines.push(`- Repository: [${plugin.repo}](${githubUrl(plugin.repo)})`);
    lines.push(`- Permissions: ${permissionChips(plugin)}`);
    lines.push(`- Entry points: ${kindLabel(plugin)}`);
    lines.push(
      `- Releases: [${plugin.repo}/releases](${githubUrl(plugin.repo, "releases")}) — installable zips ` +
        `\`${plugin.id}-<version>[-<platform>].zip\``,
    );
    lines.push("");
  }

  return lines.join("\n");
}

function main() {
  const registry = JSON.parse(readFileSync(REGISTRY_PATH, "utf8"));
  const rendered = render(registry);

  if (checkMode) {
    const current = readFileSync(OUTPUT_PATH, "utf8");
    if (current !== rendered) {
      console.error(`PLUGINS.md is stale — run 'node scripts/generate.mjs' and commit the result.`);
      process.exitCode = 1;
      return;
    }
    console.log("PLUGINS.md is up to date");
    return;
  }

  writeFileSync(OUTPUT_PATH, rendered);
  console.log(`wrote ${OUTPUT_PATH} (${registry.plugins?.length ?? 0} plugin(s))`);
}

main();
