#!/usr/bin/env node
// Resolve each registered plugin's latest published GitHub release into
// versions.json ({ "owner/repo": "version", … }).
//
//   node scripts/sync-versions.mjs [--dry-run]
//
// Runs on every push to main (merge) and daily, right before the landing
// page is dispatched: plugins.json never carries a version field — entries
// describe what a plugin is, releases say where it is. The landing page
// merges the two files when embedding the catalog, and PLUGINS.md's version
// column reads from here too.
//
// Never fails the build: a repo whose lookup errors (rate limit, no
// releases, transient 5xx) keeps its previous versions.json entry, and a
// repo with no release yet simply has no entry (the site shows "unreleased"
// until its first release lands). Repos removed from plugins.json are
// pruned automatically.
//
// SYNC_PLUGIN_FIXTURE=<path to {"repo": "version", …} JSON> replaces the
// GitHub lookups entirely — repos absent from the fixture keep their
// previous entry (mirroring a failed lookup), an explicit null drops the
// entry — used to test the rewrite path offline.

import { readFileSync, writeFileSync } from "node:fs";

const REGISTRY_PATH = "plugins.json";
const VERSIONS_PATH = "versions.json";

const GENERATED_NOTE =
  "Generated by scripts/sync-versions.mjs from each repo's latest GitHub release — DO NOT EDIT. Repo slug → latest published version (v-tagged, pre-releases excluded).";

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");

// One repo's published release version, or null on any failure (the caller
// keeps the previous entry — see the header note about never failing).
async function latestReleaseVersion(repo, currentVersion) {
  const url = `https://api.github.com/repos/${repo}/releases/latest`;
  const headers = { Accept: "application/vnd.github+json", "User-Agent": "companion-plugin-registry" };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }
  try {
    const response = await fetch(url, { headers });
    if (!response.ok) {
      console.warn(`warn: ${repo}: GitHub API returned HTTP ${response.status} — keeping ${currentVersion ?? "no entry"}`);
      return null;
    }
    const release = await response.json();
    if (release.draft || release.prerelease) return null; // unexpected from /latest, stay safe
    return release.tag_name.replace(/^v/, "");
  } catch (error) {
    console.warn(`warn: ${repo}: lookup failed (${error.message})`);
    return null;
  }
}

function readVersions() {
  try {
    const parsed = JSON.parse(readFileSync(VERSIONS_PATH, "utf8"));
    delete parsed.$comment;
    return parsed;
  } catch {
    return {}; // first run (or unreadable) — everything resolves fresh
  }
}

async function main() {
  const registry = JSON.parse(readFileSync(REGISTRY_PATH, "utf8"));
  const registered = (registry.plugins ?? []).map((plugin) => plugin.repo);
  const previous = readVersions();

  const fixturePath = process.env.SYNC_PLUGIN_FIXTURE;
  const fixture = fixturePath ? JSON.parse(readFileSync(fixturePath, "utf8")) : null;

  const out = {};
  let changed = 0;
  for (const repo of registered) {
    const fresh = fixture ? (fixture[repo] ?? null) : await latestReleaseVersion(repo, previous[repo]);
    const version = fresh ?? previous[repo] ?? null;
    if (fresh && fresh !== previous[repo]) {
      console.log(`${repo}: ${previous[repo] ?? "none"} -> ${fresh}`);
      changed++;
    }
    // No release yet (fresh and previous both null) → no entry; the site
    // renders the plugin as unreleased until its first release lands.
    if (version !== null) out[repo] = version;
  }

  const rendered = `${JSON.stringify({ $comment: GENERATED_NOTE, ...out }, null, 2)}\n`;
  if (dryRun) {
    console.log(`dry-run: ${changed} version(s) would change`);
    return;
  }

  let current = null;
  try {
    current = readFileSync(VERSIONS_PATH, "utf8");
  } catch {
    // missing file → write it
  }
  if (rendered !== current) {
    writeFileSync(VERSIONS_PATH, rendered);
    console.log(`wrote ${VERSIONS_PATH} (${Object.keys(out).length} repo(s), ${changed} changed)`);
  } else {
    console.log("versions.json already up to date");
  }
}

await main();
